import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import * as esbuild from 'esbuild';

const require = createRequire(import.meta.url);
const root = path.resolve(import.meta.dirname, '..');
const output = path.join(root, 'src', 'components', 'module', 'ide', 'terminalWebViewEngine.generated.ts');

const result = await esbuild.build({
  stdin: {
    contents: `
      import { Terminal } from '@xterm/xterm';
      import { FitAddon } from '@xterm/addon-fit';
      import { WebglAddon } from '@xterm/addon-webgl';
      window.Terminal = Terminal;
      window.FitAddon = { FitAddon };
      window.WebglAddon = { WebglAddon };
    `,
    resolveDir: root,
    sourcefile: 'terminal-engine-entry.js',
  },
  bundle: true,
  format: 'iife',
  minify: true,
  platform: 'browser',
  target: 'chrome74',
  write: false,
  legalComments: 'none',
});

const css = (await readFile(require.resolve('@xterm/xterm/css/xterm.css'), 'utf8'))
  .replace(/\/\*[\s\S]*?\*\//g, '');
const js = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
await writeFile(output, [
  '// Generated by scripts/build-terminal-webview-engine.mjs. Do not edit.',
  `export const XTERM_ENGINE_JS = ${JSON.stringify(js)};`,
  `export const XTERM_ENGINE_CSS = ${JSON.stringify(css)};`,
  '',
].join('\n'));
